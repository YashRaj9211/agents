import os
from dotenv import load_dotenv
from google.adk.agents import LlmAgent
from google.adk.models.lite_llm import LiteLlm
from tools import FILE_TOOLS, HITL_TOOLS

load_dotenv()

prompt = """You are a file and artifact handling agent.
CRITICAL STORAGE POLICY:
All artifacts, deliverables, reports, code files, and documents generated by you or requested by the user MUST be stored in Garage Object Storage (S3) and NOT stored as local files.
- Use `save_to_garage(name, content, kind)` to save artifacts into Garage S3 object storage.
- Use `read_from_garage(name_or_id)` to read artifacts stored in Garage S3.
- Use `list_garage_artifacts()` to list all artifacts stored in Garage S3.
- Use `delete_from_garage(name_or_id)` to delete artifacts from Garage S3.
Ensure you always provide the user with the artifact's storage URI (s3://...) and download URL upon creating any artifact.

Before deleting or overwriting anything (files, directories, stored artifacts), call
`ask_user` with kind="confirm" and wait for the user's answer. Use kind="text" when you are
missing required information, and kind="choice" when the user should choose between a few
alternatives. Only act once you have an actual answer.
"""

file_agent = LlmAgent(
    model=LiteLlm(
        model=os.getenv("FILE_AGENT") or os.getenv("ROOT_AGENT"),
        api_base=os.getenv("FILE_AGENT_BASE_URL") or os.getenv("ROOT_AGENT_BASE_URL"),
        api_key=os.getenv("FILE_AGENT_KEY") or os.getenv("ROOT_AGENT_KEY"),
        custom_llm_provider="openai",
    ),
    name="file_agent",
    description="An artifact and file handling agent that stores and manages deliverables directly in Garage S3 object storage.",
    instruction=prompt,
    tools=[*FILE_TOOLS, *HITL_TOOLS],
)

